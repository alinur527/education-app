'## Правило степени

Для положительного целого n производная xⁿ равна n·xⁿ⁻¹. Например, (x³)′ = 3x². Производная постоянного числа равна нулю.

## Сумма и постоянный множитель

Производную суммы находим по частям. Постоянный множитель выносим за знак производной: (c·f(x))′ = c·f′(x).

## Разберём пример

Пусть f(x) = 3x² + 2x − 7. Тогда f′(x) = 3·2x + 2 − 0 = 6x + 2. При x = 1 скорость изменения функции равна f′(1) = 8.

